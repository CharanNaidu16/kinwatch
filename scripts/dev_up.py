"""Start Kinwatch on this laptop behind a Cloudflare quick tunnel (PLAN.md §12).

    python scripts/dev_up.py            # app + tunnel; WhatsApp webhook set up if MESSENGER=whatsapp
    python scripts/dev_up.py --port 8001

Each run gets a new https://<random>.trycloudflare.com URL, so this script:
  1. generates DEVICE_TOKEN / BTS_TOKEN in .env if they are still the defaults,
  2. starts uvicorn and cloudflared and waits until the public URL answers,
  3. with WhatsApp: checks the access token, points the app's webhook at the new URL (needs WA_APP_ID),
     and subscribes the app to the WhatsApp Business Account so status events arrive,
  4. prints the camera link and sends it to the admin member on WhatsApp.
Ctrl+C stops everything. Secrets are never printed, except the camera link, which you need.
"""
from __future__ import annotations

import argparse
import asyncio
import os
import re
import secrets
import shutil
import subprocess
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import httpx  # noqa: E402

from backend.config import Settings  # noqa: E402

TUNNEL_URL = re.compile(r"https://[a-z0-9-]+\.trycloudflare\.com")
DEFAULT_TOKENS = {"DEVICE_TOKEN": "change-me-device", "BTS_TOKEN": "change-me-bts"}
CLOUDFLARED_PATHS = [Path(r"C:\Program Files (x86)\cloudflared\cloudflared.exe"),
                     Path(r"C:\Program Files\cloudflared\cloudflared.exe")]


def find_tunnel_url(line: str) -> str | None:
    m = TUNNEL_URL.search(line)
    return m.group(0) if m else None


def cloudflared_path() -> str | None:
    found = shutil.which("cloudflared")
    if found:
        return found
    links = Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft" / "WinGet" / "Links" / "cloudflared.exe"
    for p in [links, *CLOUDFLARED_PATHS]:
        if p.exists():
            return str(p)
    return None


def ensure_tokens(env_path: Path, settings: Settings) -> bool:
    """Append random tokens for any still at their default. Returns True if .env changed."""
    current = {"DEVICE_TOKEN": settings.device_token.get_secret_value(),
               "BTS_TOKEN": settings.bts_token.get_secret_value()}
    missing = [k for k, default in DEFAULT_TOKENS.items() if current[k] == default]
    if not missing:
        return False
    raw = env_path.read_bytes() if env_path.exists() else b""
    lines = ["", "# generated by scripts/dev_up.py"] + [f"{k}={secrets.token_urlsafe(24)}" for k in missing]
    with env_path.open("ab") as f:
        f.write(("" if raw.endswith(b"\n") or not raw else "\n").encode() + "\n".join(lines).encode() + b"\n")
    return True


async def whatsapp_setup(settings: Settings, public_url: str, http: httpx.AsyncClient) -> list[str]:
    """Check the token, register the webhook (if WA_APP_ID is set), subscribe the app to the WABA.

    Returns human-readable lines; raises RuntimeError if the access token doesn't work.
    """
    base = f"https://graph.facebook.com/{settings.wa_graph_version}"
    token = settings.wa_access_token.get_secret_value() if settings.wa_access_token else ""
    auth = {"Authorization": f"Bearer {token}"}
    out: list[str] = []

    r = await http.get(f"{base}/{settings.wa_phone_number_id}", headers=auth,
                       params={"fields": "verified_name,quality_rating"})
    if r.status_code != 200:
        err = r.json().get("error", {}) if r.headers.get("content-type", "").startswith("application/json") else {}
        raise RuntimeError(f"WhatsApp token check failed (HTTP {r.status_code}, code {err.get('code')}): "
                           f"{err.get('message', r.text[:200])}. Code 190 means the token expired.")
    info = r.json()
    out.append(f"WhatsApp number OK: {info.get('verified_name', '?')} (quality {info.get('quality_rating', '?')})")

    callback = f"{public_url}/webhooks/whatsapp"
    if settings.wa_app_id and settings.wa_app_secret and settings.wa_verify_token:
        app_token = f"{settings.wa_app_id}|{settings.wa_app_secret.get_secret_value()}"
        r = await http.post(f"{base}/{settings.wa_app_id}/subscriptions", data={
            "object": "whatsapp_business_account", "callback_url": callback, "fields": "messages",
            "verify_token": settings.wa_verify_token.get_secret_value(), "access_token": app_token})
        if r.status_code == 200 and r.json().get("success"):
            out.append(f"Webhook set to {callback}")
        else:
            out.append(f"Could not set the webhook automatically (HTTP {r.status_code}): {r.text[:200]}")
            out.append(f"  Paste it by hand: App dashboard > WhatsApp > Configuration > Callback URL = {callback}")
    else:
        out.append(f"Set WA_APP_ID to update the webhook automatically. For now paste it by hand:")
        out.append(f"  App dashboard > WhatsApp > Configuration > Callback URL = {callback}, field 'messages'")

    if settings.wa_business_account_id:
        r = await http.post(f"{base}/{settings.wa_business_account_id}/subscribed_apps", headers=auth)
        ok = r.status_code == 200 and r.json().get("success")
        out.append("App subscribed to the WhatsApp Business Account" if ok
                   else f"Subscribing the app to the WABA failed (HTTP {r.status_code}): {r.text[:200]}")
    else:
        out.append("WA_BUSINESS_ACCOUNT_ID is not set, so the app can't be subscribed (no status events).")
    return out


def _pump(stream, sink: list[str], found: threading.Event, prefix: str) -> None:
    for raw in iter(stream.readline, b""):
        line = raw.decode(errors="replace").rstrip()
        if find_tunnel_url(line) and not found.is_set():
            sink.append(find_tunnel_url(line))
            found.set()
        if prefix == "app" and line:
            print(f"[app] {line}")


def _wait_http(url: str, timeout: float) -> bool:
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            if httpx.get(url, timeout=5).status_code == 200:
                return True
        except httpx.HTTPError:
            pass
        time.sleep(1)
    return False


async def _send_camera_link(settings: Settings, link: str) -> str:
    from backend.household import ensure_household
    from backend.messaging.whatsapp import WhatsAppMessenger
    from backend.storage import Storage

    storage = Storage(settings.db_path)
    try:
        storage.migrate()
        admins = [m for m in storage.members(ensure_household(storage, settings)) if m.is_admin]
        if not admins:
            return "No admin in FAMILY_MEMBERS_JSON, so the camera link wasn't sent on WhatsApp."
        await WhatsAppMessenger(settings).send_text(
            admins[0], f"Kinwatch camera link (open it on the camera phone):\n{link}")
        return f"Camera link sent to {admins[0].name} on WhatsApp."
    except Exception as exc:  # e.g. outside the 24-hour window
        return f"Couldn't send the camera link on WhatsApp ({exc}). Open it from this terminal instead."
    finally:
        storage.close()


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8000)
    args = ap.parse_args()

    env_path = ROOT / ".env"
    if ensure_tokens(env_path, Settings()):
        print("Generated DEVICE_TOKEN and/or BTS_TOKEN in .env.")
    settings = Settings()

    cloudflared = cloudflared_path()
    if cloudflared is None:
        sys.exit("cloudflared not found. Install it with:  winget install Cloudflare.cloudflared")

    app = subprocess.Popen([sys.executable, "-m", "uvicorn", "backend.main:app", "--host", "127.0.0.1",
                            "--port", str(args.port)], cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    threading.Thread(target=_pump, args=(app.stdout, [], threading.Event(), "app"), daemon=True).start()
    procs = [app]
    try:
        if not _wait_http(f"http://127.0.0.1:{args.port}/healthz", 30):
            sys.exit("The app didn't start; see the [app] lines above.")
        tunnel = subprocess.Popen([cloudflared, "tunnel", "--no-autoupdate", "--url", f"http://127.0.0.1:{args.port}"],
                                  stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        procs.append(tunnel)
        urls: list[str] = []
        found = threading.Event()
        threading.Thread(target=_pump, args=(tunnel.stdout, urls, found, "tunnel"), daemon=True).start()
        if not found.wait(45):
            sys.exit("cloudflared didn't report a tunnel URL within 45 s.")
        public = urls[0]
        print(f"Tunnel: {public}  (waiting for it to answer...)")
        if not _wait_http(f"{public}/healthz", 60):
            sys.exit("The tunnel URL isn't reachable yet; try running the script again.")

        camera = f"{public}/phone?d={settings.device_token.get_secret_value()}"
        if settings.messenger == "whatsapp":
            async def setup() -> list[str]:
                async with httpx.AsyncClient(timeout=20) as http:
                    lines = await whatsapp_setup(settings, public, http)
                return [*lines, await _send_camera_link(settings, camera)]
            for line in asyncio.run(setup()):
                print(line)
        print()
        print(f"Camera link (open on the camera phone): {camera}")
        print(f"Budget: {public}/api/budget  (needs the BTS token)")
        print("Running. Press Ctrl+C to stop.")
        while all(p.poll() is None for p in procs):
            time.sleep(1)
        print("A process exited; stopping.")
    except KeyboardInterrupt:
        print("\nStopping.")
    finally:
        for p in reversed(procs):
            if p.poll() is None:
                p.terminate()
                try:
                    p.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    p.kill()


if __name__ == "__main__":
    main()
